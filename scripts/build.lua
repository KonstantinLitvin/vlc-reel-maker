#!/usr/bin/env luajit
-- scripts/build.lua
-- Micro-bundler for ReelMaker VLC extension
-- Bundles modular Lua sources in src/ into dist/ bundles

local v_chunk = loadfile("src/version.lua")
local version = v_chunk and v_chunk() or "1.2"

local function ensure_dist_dir()
    local is_win = (package and package.config and package.config:sub(1, 1) == "\\") or false
    if is_win then
        os.execute('if not exist dist mkdir dist')
    else
        os.execute('mkdir -p dist 2>/dev/null')
    end
end

local function bundle_target(lang, out_path)
    local locale_file = string.format("src/locales/%s.lua", lang)

    local check_locale = io.open(locale_file, "r")
    if not check_locale then
        io.stderr:write(string.format("Error: Locale catalog '%s' not found for language '%s'\n", locale_file, lang))
        return false
    end
    check_locale:close()

    local modules = {
        { name = "locale",             file = locale_file },
        { name = "version",            file = "src/version.lua" },
        { name = "timecode",           file = "src/timecode.lua" },
        { name = "scene",              file = "src/scene.lua" },
        { name = "platform",           file = "src/platform.lua" },
        { name = "cutter_service",     file = "src/cutter_service.lua" },
        { name = "scene_repository",   file = "src/scene_repository.lua" },
        { name = "vlc_player_adapter", file = "src/vlc_player_adapter.lua" },
        { name = "app_controller",     file = "src/app_controller.lua" },
        { name = "main",               file = "src/main.lua" }
    }

    local out_f, err = io.open(out_path, "w")
    if not out_f then
        io.stderr:write("Error opening output file " .. out_path .. ": " .. tostring(err) .. "\n")
        return false
    end

    -- Write header
    out_f:write(string.format([=[-- VLC Lua Extension : ReelMaker v%s
-- Version           : %s
-- Language          : %s
-- Author            : Konstantin Litvin
-- Description       : Fragment capture (Mark In / Mark Out), reel navigation, FFmpeg cutting, and .scn persistence
--
-- NOTE: THIS IS A COMPILED BUNDLE GENERATED BY scripts/build.lua
-- DO NOT EDIT THIS FILE DIRECTLY. EDIT THE MODULAR SOURCES IN src/

local __modules = {}
local __loaded = {}
local function __define(name, factory)
    __modules[name] = factory
end
local __orig_require = require
local function require(name)
    if __modules[name] then
        if __loaded[name] == nil then
            __loaded[name] = __modules[name]()
        end
        return __loaded[name]
    end
    if __orig_require then
        return __orig_require(name)
    end
    error("Module not found: " .. tostring(name))
end

]=], version, version, lang))

    -- Bundle each module
    for _, mod in ipairs(modules) do
        local in_f, in_err = io.open(mod.file, "r")
        if not in_f then
            io.stderr:write("Error reading module " .. mod.file .. ": " .. tostring(in_err) .. "\n")
            out_f:close()
            return false
        end
        local content = in_f:read("*a")
        in_f:close()

        out_f:write(string.format("--------------------------------------------------\n-- Module: %s (%s)\n--------------------------------------------------\n", mod.name, mod.file))
        out_f:write(string.format('__define("%s", function(...)\n', mod.name))
        out_f:write(content)
        if not content:match("\n$") then
            out_f:write("\n")
        end
        out_f:write("end)\n\n")
    end

    -- Write footer launcher
    out_f:write([=[--------------------------------------------------
-- Initialize extension
--------------------------------------------------
require("main")
]=])

    out_f:close()

    local check_f = io.open(out_path, "r")
    local total_bytes = check_f and check_f:seek("end") or 0
    if check_f then check_f:close() end

    print(string.format("[BUILD] Successfully bundled %d modules (locale: %s) into %s (%d bytes)", #modules, lang, out_path, total_bytes))
    return true
end

ensure_dist_dir()

local env_lang = os.getenv("LANG_TARGET")
local target = (arg and arg[1]) or (env_lang and env_lang ~= "" and env_lang)

if not target or target == "all" then
    local ok_en = bundle_target("en", "dist/reel-maker-en.lua")
    local ok_ru = bundle_target("ru", "dist/reel-maker-ru.lua")
    local ok_def = bundle_target("en", "dist/reel-maker.lua")
    if not (ok_en and ok_ru and ok_def) then
        os.exit(1)
    end
else
    local out_path = (arg and arg[2]) or "dist/reel-maker.lua"
    local ok = bundle_target(target, out_path)
    if not ok then
        os.exit(1)
    end
end
